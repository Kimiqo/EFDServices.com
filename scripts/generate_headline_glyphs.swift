import Foundation
import CoreText
import CoreGraphics

// Run from the site root: swift -module-cache-path /tmp/efd-swift-cache scripts/generate_headline_glyphs.swift
// Only the finished vector letter outlines are used by the website; no fonts are shipped.
let headlines: [(String, [String])] = [
    ("headlineLines", ["Your identity.", "Beautifully", "stitched."]),
    ("galleryHeadlineLines", ["A little inspiration.", "A world of possibilities."]),
    ("galleryMobileHeadlineLines", ["A little", "inspiration.", "A world of", "possibilities."]),
    ("contactHeadlineLines", ["Your idea.", "Let’s talk about it."]),
    ("storyHeadlineLines", ["Our story.", "Written in thread."])
]
var source = "// Georgia letter outlines generated by scripts/generate_headline_glyphs.swift.\n"
for (name, lines) in headlines {
var output: [[String: Any]] = []
for (lineIndex, line) in lines.enumerated() {
    let accent = name == "galleryMobileHeadlineLines" ? lineIndex >= 2 : lineIndex == lines.count - 1
    let font = CTFontCreateWithName((accent ? "Georgia-Italic" : "Georgia") as CFString, 100, nil)
    var glyphs: [[String: Any]] = []
    var x: CGFloat = 6
    for character in line.utf16 {
        var code = character
        var glyph: CGGlyph = 0
        CTFontGetGlyphsForCharacters(font, &code, &glyph, 1)
        var advance = CGSize.zero
        CTFontGetAdvancesForGlyphs(font, .horizontal, &glyph, &advance, 1)
        if let outline = CTFontCreatePathForGlyph(font, glyph, nil) {
            var segments: [String] = []
            func point(_ p: CGPoint) -> String { String(format: "%.2f %.2f", x + p.x, 93 - p.y) }
            outline.applyWithBlock { element in
                let e = element.pointee
                switch e.type {
                case .moveToPoint: segments.append("M" + point(e.points[0]))
                case .addLineToPoint: segments.append("L" + point(e.points[0]))
                case .addQuadCurveToPoint: segments.append("Q" + point(e.points[0]) + " " + point(e.points[1]))
                case .addCurveToPoint: segments.append("C" + point(e.points[0]) + " " + point(e.points[1]) + " " + point(e.points[2]))
                case .closeSubpath: segments.append("Z")
                @unknown default: break
                }
            }
            glyphs.append(["letter": String(UnicodeScalar(character)!), "path": segments.joined(separator: " ")])
        }
        x += advance.width - 4
    }
    output.append(["text": line, "width": x + 10, "glyphs": glyphs, "accent": accent])
}
let json = try JSONSerialization.data(withJSONObject: output, options: [.prettyPrinted, .sortedKeys])
source += "export const \(name) = " + String(data: json, encoding: .utf8)! + ";\n"
}
let destination = URL(fileURLWithPath: FileManager.default.currentDirectoryPath).appendingPathComponent("src/data/headlineGlyphs.ts")
try source.write(to: destination, atomically: true, encoding: .utf8)
